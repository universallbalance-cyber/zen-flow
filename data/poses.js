export const getDailyPose = () => {
  const today = new Date();
  const dayOfYear = Math.floor(
    (today - new Date(today.getFullYear(), 0, 0)) / 1000 / 60 / 60 / 24
  );
  return poses[dayOfYear % poses.length];
};

export const getDailyAffirmation = () => {
  const today = new Date();
  const dayOfYear = Math.floor(
    (today - new Date(today.getFullYear(), 0, 0)) / 1000 / 60 / 60 / 24
  );
  return affirmations[dayOfYear % affirmations.length];
};

export const getPosesByCategory = (category) => {
  if (category === "Any") return poses;
  return poses.filter((p) => p.category === category);
};

export const getRandomPose = (category = "Any") => {
  const pool = getPosesByCategory(category);
  return pool[Math.floor(Math.random() * pool.length)];
};